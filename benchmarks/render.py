# --------------------------------------------------------------------------- formatting
def num(v, digits: int = 3) -> str:
    if v is None or (isinstance(v, float) and not math.isfinite(v)):
        return DASH
    return f"{v:,.{digits}f}"


def seconds(s) -> str:
    if s is None:
        return DASH
    if s < 0.01:
        return "<0.01"
    return f"{s:.2f}" if s < 10 else f"{s:.1f}" if s < 100 else f"{s:,.0f}"


STALL_SHARE = 0.1  # a cell during which the cgroup stalled on memory for more than this share of its wall time


def stalled(cell: dict) -> bool:
    """True when the cell's timings may be stretched by memory throttling of the shared cgroup.

    Uses the stricter of the two PSI totals the cell records (``memory_stall_s``): ``some``, the
    time during which at least one task of the cgroup waited for memory. It also counts stalls of
    other processes in the group, so it marks every cell that ``full`` would mark and possibly more.
    """
    stall = cell.get("memory_stall_s") or {}
    return max(stall.get("some", 0.0), stall.get("full", 0.0)) > STALL_SHARE * max(cell.get("wall_time_s") or 0.0,
                                                                                   1e-9)


def times(cell: dict) -> list[str]:
    """Fit and predict seconds, marked with a dagger when the cell ran under memory throttling."""
    mark = " †" if stalled(cell) else ""
    return [seconds(cell["fit_s"]) + mark, seconds(cell["predict_s"]) + mark]


def md_table(header: list[str], rows: list[list[str]], align: str | None = None) -> str:
    esc = lambda s: str(s).replace("|", "\\|")  # noqa: E731
    align = align or "l" + "r" * (len(header) - 1)
    rule = ["---:" if a == "r" else ":---" for a in align]
    return "\n".join(["| " + " | ".join(esc(h) for h in header) + " |", "| " + " | ".join(rule) + " |",
                      *["| " + " | ".join(esc(c) for c in row) + " |" for row in rows]])


def anchor(dataset: str, table_id: str | None = None) -> str:
    return f"{dataset}-{table_id}".lower().replace("_", "-") if table_id else dataset.lower().replace("_", "-")


def cite(source: dict | None) -> str:
    if not source:
        return DASH
    names = [a.strip() for a in (source.get("authors") or "").split(",") if a.strip()]
    lead = names[0].split()[-1] if names else "?"
    who = lead + (" et al." if len(names) > 2 else f" and {names[1].split()[-1]}" if len(names) == 2 else "")
    doi = f", doi:{source['doi']}" if source.get("doi") else (f", {source['url']}" if source.get("url") else "")
    return f"{who} ({source.get('year', '?')}), {source.get('venue', '')}{doi}"


def display(cell: dict, lang: int) -> str:
    return (cell.get("display") or [cell["method"]] * 2)[lang]


# --------------------------------------------------------------------------- one result table
def _is_baseline(cell) -> bool:
    return cell["method"] == matrix.BASELINE


def _label_shown(cells, key: str) -> bool:
    """Show a label column when the test rows hold more than one value, i.e. when the training-majority
    baseline does not score exactly 100 %."""
    values = [c["pooled"].get(key) for c in cells if c.get("status") == "ok"]
    if not values or all(v is None for v in values):
        return False
    base = [c["pooled"].get(key) for c in cells if c.get("status") == "ok" and _is_baseline(c)]
    return not base or base[0] != 100.0


def result_table(table: dict, lang: int) -> str:
    cells = table["cells"]
    ok = [c for c in cells if c.get("status") == "ok"]
    multi = len(table.get("protocol", {}).get("folds", [])) > 1
    if table["runner"] == "labels":
        header = [t("method", lang), t("preprocessing", lang), t("room_acc", lang), t("fold_acc", lang),
                  t("fit", lang), t("predict", lang), t("peak", lang)]
        best = max((c["pooled"]["accuracy"] for c in ok if not _is_baseline(c)), default=None)
        rows = []
        for c in cells:
            if c.get("status") != "ok":
                rows.append([display(c, lang), matrix.display_preprocess(c["preprocess"], lang),
                             T["status"][c.get("status", "not-run")][lang], DASH, DASH, DASH, DASH])
                continue
            acc = c["pooled"]["accuracy"]
            folds = [f["metrics"]["accuracy"] for f in c["folds"]]
            cell = num(acc, 2)
            rows.append([display(c, lang), matrix.display_preprocess(c["preprocess"], lang),
                         f"**{cell}**" if acc == best and not _is_baseline(c) else cell,
                         f"{min(folds):.2f}–{max(folds):.2f}", *times(c), f"{c['peak_rss_mb']:,.0f}"])
        return md_table(header, rows, "ll" + "r" * 5)
    floor, building = _label_shown(cells, "floor_accuracy"), _label_shown(cells, "building_accuracy")
    ipin = floor or building  # with one floor and one building the IPIN score is just the P75 error
    header = [t("method", lang), t("preprocessing", lang), t("mean", lang), t("median", lang), "P75", "P90"]
    header += [t("floor", lang)] * floor + [t("building", lang)] * building + [t("ipin", lang)] * ipin
    header += [t("folds", lang)] * multi + [t("fit", lang), t("predict", lang), t("peak", lang)]
    best = min((c["pooled"]["mean_error"] for c in ok if not _is_baseline(c)), default=None)
    rows = []
    for c in cells:
        name, pre = display(c, lang), matrix.display_preprocess(c["preprocess"], lang)
        if c.get("status") != "ok":
            status = T["status"].get(c.get("status", "not-run"), (c.get("status"),) * 2)[lang]
            rows.append([name, pre, status] + [DASH] * (len(header) - 3))
            continue
        p = c["pooled"]
        mean = num(p["mean_error"])
        row = [name, pre, f"**{mean}**" if p["mean_error"] == best else mean, num(p["median_error"]),
               num(p["p75_error"]), num(p["p90_error"])]
        row += [num(p.get("floor_accuracy"), 2)] * floor + [num(p.get("building_accuracy"), 2)] * building
        row += [num(p.get("ipin_score"))] * ipin
        if multi:
            means = [f["metrics"]["mean_error"] for f in c["folds"]]
            row.append(f"{min(means):.2f}–{max(means):.2f}")
        row += [*times(c), f"{c['peak_rss_mb']:,.0f}"]
        rows.append(row)
    return md_table(header, rows, "ll" + "r" * (len(header) - 2))


def _data_line(table: dict, lang: int) -> str:
    ds = table.get("dataset", {})
    split_name = (lambda k: SPLIT_ZH.get(k, k)) if lang == ZH else (lambda k: k)  # noqa: E731
    sizes = ", ".join(f"{split_name(k)} {v:,}" for k, v in (ds.get("n_samples") or {}).items())
    digests = {}
    for split, sha in (ds.get("sha256") or {}).items():
        values = list(sha.values()) if isinstance(sha, dict) else sha if isinstance(sha, list) else [sha]
        values = [v for v in values if v]
        key = (tuple(v[:12] for v in values) if len(values) <= 2 else
               (f"{len(values)} files" if lang == EN else f"{len(values)} 个文件",))
        digests.setdefault(key, []).append(split)
    sha = "; ".join(f"{'/'.join(split_name(x) for x in splits)} `{', '.join(d)}`" for d, splits in digests.items())
    opts = ", ".join(f"{k}={v}" for k, v in (table.get("options") or {}).items())
    rows = ("rows" if lang == EN else "行")
    base = f"`{ds.get('name', '?')}`" + (f" ({opts})" if opts else "") + f": {sizes} {rows}"
    return base + (f"; sha256 {sha}" if sha else "")


def _protocol_line(table: dict, lang: int) -> str:
    proto = table.get("protocol", {})
    folds = proto.get("folds", [])
    name = proto.get("name", table.get("protocol_spec"))
    if len(folds) == 1:
        f = folds[0]
        unused = f.get("n_unused", 0)
        extra = (f", {unused:,} rows unused" if lang == EN else f"，{unused:,} 行未使用") if unused else ""
        sizes = (f"train {f['n_train']:,} / test {f['n_test']:,}" if lang == EN else
                 f"训练 {f['n_train']:,} / 测试 {f['n_test']:,}") + extra
    else:
        n_test = sum(f["n_test"] for f in folds)
        sizes = (f"{len(folds)} {t('folds_word', lang)}, {n_test:,} test rows; {t('each_once', lang)}" if lang == EN
                 else f"{len(folds)} {t('folds_word', lang)}，共 {n_test:,} 条测试行；{t('each_once', lang)}")
    summary = PROTOCOL_ZH.get(name, proto.get("summary", "")) if lang == ZH else proto.get("summary", "")
    return f"`{name}`: {summary} ({sizes})"


def limit_reason(cell: dict, lang: int) -> str:
    """Why a cell has no result, with the CPU time and memory stall it had used when it was stopped."""
    reason = cell.get("reason") or cell.get("status", "")
    if lang == ZH:
        m = re.fullmatch(r"did not finish within the (\d+)-minute limit", reason)
        reason = f"未能在 {m[1]} 分钟限制内完成" if m else reason
        m = re.fullmatch(r"stopped at (\d+) MB resident, above the (\d+) MB limit per process", reason)
        reason = f"常驻内存达到 {m[1]} MB，超过每进程 {m[2]} MB 的限制，已终止" if m else reason
    stall = (cell.get("memory_stall_s") or {}).get("some")
    cpu = cell.get("cpu_time_s")
    if cell.get("status") not in ("timeout", "memory") or cpu is None:
        return reason
    if lang == EN:
        extra = f"{cpu:,.0f} s of CPU time used" + (f"; the cgroup was stalled on memory for {stall:,.0f} s of the "
                                                    f"{cell['wall_time_s']:,.0f} s" if stall else "")
    else:
        extra = f"已用 CPU 时间 {cpu:,.0f} s" + (f"；在 {cell['wall_time_s']:,.0f} s 中控制组因内存停顿 {stall:,.0f} s"
                                               if stall else "")
    return f"{reason} ({extra})" if lang == EN else f"{reason}（{extra}）"


def table_section(table: dict, lang: int) -> list[str]:
    title = table["title"]["en" if lang == EN else "zh"]
    out = [f'<a id="{anchor(table["dataset"]["name"] if "dataset" in table else "", table["id"])}"></a>',
           f"### {title}", ""]
    if "protocol" in table:
        colon = ": " if lang == EN else "："
        out += [f"- {t('protocol', lang)}{colon}{_protocol_line(table, lang)}",
                f"- {t('data', lang)}{colon}{_data_line(table, lang)}",
                f"- {t('units', lang)}{colon}{units(table.get('units'), lang)}"]
        example = next((c for c in table["cells"] if c.get("status") == "ok" and c["method"] == "wknn"),
                       next((c for c in table["cells"] if c.get("status") == "ok"), None))
        if example:  # without -q, which (with no --out) would print nothing
            shown = " ".join(w for w in example["command"].split(" ") if w != "-q")
            out.append(f"- {t('one_cell', lang)}{colon}`{shown}`")
        out.append("")
    out += [result_table(table, lang), ""]
    failed = [c for c in table["cells"] if c.get("status") not in ("ok", "not-run", None)]
    if table["skips"] or failed:
        out.append(f"**{t('not_run', lang)}**:")
        for s in table["skips"]:
            out.append(f"- {s['method']}: {s['en' if lang == EN else 'zh']}")
        for c in failed:
            out.append(f"- {display(c, lang)} ({matrix.display_preprocess(c['preprocess'], lang)}): "
                       f"{limit_reason(c, lang)}")
        out.append("")
    if table["notes"]:
        out += [f"**{t('notes', lang)}**:"] + [f"- {n['en' if lang == EN else 'zh']}" for n in table["notes"]] + [""]
    return out


