def _run_stats(docs: dict) -> dict:
    """Counts and costs over every cell that ran, whatever its outcome."""
    cells = [c for doc in docs.values() for tb in doc["tables"] for c in tb["cells"] if c.get("wall_time_s")]
    ok = [c for c in cells if c.get("status") == "ok"]
    with_stall = [c for c in ok if c.get("memory_stall_s")]
    reruns = [c["rerun_check"] for c in ok if c.get("rerun_check")]
    return {"run": len(cells), "ok": len(ok), "limit": sum(c["status"] in ("timeout", "memory") for c in cells),
            "failed": sum(c["status"] == "failed" for c in cells),
            "hours": sum(c["wall_time_s"] for c in cells) / 3600,
            "cpu_hours": sum(c.get("cpu_time_s") or 0.0 for c in cells) / 3600,
            "with_cpu": sum(c.get("cpu_time_s") is not None for c in cells),
            "peak": max((c["peak_rss_mb"] for c in ok), default=0.0),
            "with_stall": len(with_stall), "stalled": sum(stalled(c) for c in with_stall),
            "reruns": len(reruns), "rerun_worst": max((r["largest_difference"] for r in reruns
                                                       if r["largest_difference"] is not None), default=0.0),
            "rerun_incomparable": sum(r["largest_difference"] is None for r in reruns)}


def code_versions(docs: dict) -> list[tuple[str, int, dict | None]]:
    """``(source digest, finished cells that ran it, code block)`` for every library version the cells
    record, most cells first. The code block (git state, whether it was a ``--freeze`` copy, when it
    was taken) comes from the result files' ``harness.code`` / ``harness.code_history``."""
    counts: dict[str, int] = {}
    for doc in docs.values():
        for tb in doc["tables"]:
            for c in tb["cells"]:
                if c.get("status") == "ok" and c.get("source_sha256"):
                    counts[c["source_sha256"]] = counts.get(c["source_sha256"], 0) + 1
    blocks: dict[str, dict] = {}
    for doc in docs.values():
        h = doc.get("harness") or {}
        for code in [h.get("code"), *(h.get("code_history") or [])]:
            if code and code.get("source_sha256"):
                blocks.setdefault(code["source_sha256"], code)
    return [(d, n, blocks.get(d)) for d, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))]


def _code_text(digest: str, n: int, code: dict | None, lang: int) -> str:
    cells = (f"{n} cells" if n != 1 else "1 cell") if lang == EN else f"{n} 个单元格"
    if not code:
        return (f"`{digest[:16]}` ({cells}; how this code was obtained is not recorded)" if lang == EN else
                f"`{digest[:16]}`（{cells}；未记录该代码的来源）")
    git = code.get("git") or {}
    when = (code.get("taken") or "?")[:16].replace("T", " ")
    frozen = code.get("frozen", "taken" in code)
    commit, branch = git.get("commit", "?")[:12], git.get("branch", "?")
    if lang == EN:
        how = (f"a copy frozen with `run.py --freeze` at {when} UTC" if frozen else
               f"the working tree as of {when} UTC (not frozen)")
        return (f"`{digest[:16]}` ({cells}): {how} from git commit `{commit}` on `{branch}`"
                + (" with uncommitted changes" if git.get("dirty") else ""))
    how = (f"{when} UTC 用 `run.py --freeze` 冻结的副本" if frozen else f"{when} UTC 的工作区（未冻结）")
    return (f"`{digest[:16]}`（{cells}）：{how}，来自 `{branch}` 分支的 git 提交 `{commit}`"
            + ("，含未提交的修改" if git.get("dirty") else ""))


def verification_line(verification: dict, lang: int) -> str:
    """The ``run.py --verify --record-verification`` summary: how many cells, which code, the largest difference."""
    rows = verification["cells"]
    compared = [r for r in rows if r.get("largest_difference") is not None]
    missing = len(rows) - len(compared)
    worst = max((r["largest_difference"] for r in compared), default=0.0)
    rerun = sorted({r.get("rerun_source_sha256") for r in rows if r.get("rerun_source_sha256")})
    stored = sorted({r.get("stored_source_sha256") for r in rows if r.get("stored_source_sha256")})
    other = bool(rerun) and rerun != stored
    code = ", ".join(f"`{d[:16]}`" for d in rerun) or "?"
    date = verification.get("created", "")[:10]
    if lang == EN:
        return (f"- Determinism check: {len(rows)} cells were run again with `run.py --verify` ({date}, library "
                f"source digest {code}"
                + (", a later version of the code than the one the cells recorded: the check also shows that "
                   "the changes made since leave these numbers unchanged" if other and worst == 0 and not missing
                   else ", not the version the cells recorded" if other else "")
                + f"); largest difference over all their pooled and per-fold metrics: {worst:.3g}"
                + (" (identical)" if worst == 0 else "")
                + (f"; {missing} could not be compared (see `results/verification.json`)" if missing else "") + ".")
    return (f"- 确定性检查：{len(rows)} 个单元格用 `run.py --verify` 再次运行（{date}，库源码摘要 {code}"
            + ("，比单元格记录的代码更新：这也说明此后的代码修改没有改变这些数字"
               if other and worst == 0 and not missing
               else "，与单元格记录的版本不同" if other else "")
            + f"）；其合并及各折指标的最大差异：{worst:.3g}" + ("（完全相同）" if worst == 0 else "")
            + (f"；{missing} 个无法比较（见 `results/verification.json`）" if missing else "") + "。")


