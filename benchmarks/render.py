def _load_optional(path: Path) -> dict | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def load_docs(results_dir: Path) -> dict:
    docs = {}
    for dataset in matrix.DATASET_ORDER:
        path = results_dir / f"{dataset}.json"
        if path.is_file():
            docs[dataset] = json.loads(path.read_text(encoding="utf-8"))
    return docs


# section names where the literature file has none (HALOC, H-WILD) or names a subset of the tables
NAMES = {"haloc": "HALOC", "hwild": "H-WILD", "csi_fingerprint": "CSI fingerprint dataset (Zhu et al., four rooms)"}


def dataset_name(doc: dict, dataset: str) -> str:
    return NAMES.get(dataset) or doc.get("literature", {}).get("display_name") or dataset


def document(docs: dict, verification: dict | None, lang: int, crosscheck: dict | None = None) -> str:
    """The whole Markdown document in one language (``EN`` or ``ZH``) from the loaded result files."""
    out = [f"# {t('title', lang)}", "", t("generated", lang), "", t("intro", lang), ""]
    toc = [f"- [{t('summary', lang)}](#{'summary' if lang == EN else '总览'})"]
    for dataset in matrix.DATASET_ORDER:
        if dataset in docs:
            name = dataset_name(docs[dataset], dataset)
            toc.append(f"- [{name}](#{anchor(dataset)})")
    out += [f"## {t('contents', lang)}", "", *toc, ""]
    out += summary_section(docs, lang)
    out += observations_section(docs, lang)
    out += setup_section(docs, verification, lang)
    out += checks_section(docs, lang, crosscheck)
    out += methods_section(lang)
    for dataset in matrix.DATASET_ORDER:
        doc = docs.get(dataset)
        if not doc:
            continue
        first = next((tb for tb in doc["tables"] if "dataset" in tb), {})
        meta = first.get("dataset", {})
        name = dataset_name(doc, dataset)
        out += [f'<a id="{anchor(dataset)}"></a>', "", f"## {name} (`{dataset}`)", ""]
        doi = meta.get("doi")
        facts = [meta.get("citation"), f"doi:{doi}" if doi and doi not in (meta.get("citation") or "") else None,
                 (("license: " if lang == EN else "许可：") + meta["license"]) if meta.get("license") else None]
        out += ["; ".join(f for f in facts if f) + ".", ""]
        for tb in doc["tables"]:
            tb = {**tb, "dataset": tb.get("dataset", {"name": dataset})}
            out += table_section(tb, lang)
        out += published_section(doc["literature"], lang)
    out += reproduce_section(lang)
    return "\n".join(out).rstrip() + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--results-dir", type=Path, default=HERE / "results")
    p.add_argument("--docs-dir", type=Path, default=HERE.parent / "docs")
    args = p.parse_args(argv)
    docs = load_docs(args.results_dir)
    if not docs:
        raise SystemExit(f"no result files in {args.results_dir}")
    verification, crosscheck = (_load_optional(args.results_dir / f"{name}.json") for name in ("verification",
                                                                                                 "crosscheck"))
    args.docs_dir.mkdir(parents=True, exist_ok=True)
    (args.docs_dir / "benchmarks.md").write_text(document(docs, verification, EN, crosscheck), encoding="utf-8")
    (args.docs_dir / "benchmarks_zh.md").write_text(document(docs, verification, ZH, crosscheck), encoding="utf-8")
    print(f"wrote {args.docs_dir / 'benchmarks.md'} and {args.docs_dir / 'benchmarks_zh.md'}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
