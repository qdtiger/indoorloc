    reps = {"positive": [0, 0], "exponential": [0, 0], "powed": [0, 0]}  # [better than fill, tables]
    below_baseline, horus = [], [0, 0]
    raw_horus = [0, 0, 0]  # [raw beats filled Horus, raw beats WKNN, tables with both Horus cells]
    ensembles = {matrix.ENSEMBLE: ("wknn", matrix.RF, "horus"), matrix.ENSEMBLE_TREES: ("wknn", matrix.RF, matrix.ET)}
