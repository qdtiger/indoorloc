    for dataset in matrix.DATASET_ORDER:
        for tb in (docs.get(dataset) or {}).get("tables", []):
            if tb["runner"] != "cli" or not tb["cells"]:
                continue
            cells = _cells_by(tb)
            main = tb["cells"][0]["preprocess"]  # the preprocessing every method of the table runs with
            base = next((c for c in cells.values() if _is_baseline(c)), None)
